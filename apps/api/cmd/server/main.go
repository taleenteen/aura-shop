package main

import (
	"context"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"aura-tech/api/internal/config"
	"aura-tech/api/internal/database"
	"aura-tech/api/internal/handler"
	appMiddleware "aura-tech/api/internal/middleware"
	"aura-tech/api/internal/models"
	"aura-tech/api/internal/repository"
	"aura-tech/api/internal/service"
	"aura-tech/api/internal/storage"

	"github.com/go-chi/chi/v5"
	"github.com/go-chi/chi/v5/middleware"
	"github.com/go-chi/cors"
	httpSwagger "github.com/swaggo/http-swagger/v2"

	_ "aura-tech/api/docs" // generated by `make swagger`
)

//	@title			AURA Tech API
//	@version		1.0
//	@description	REST API for the AURA Tech store: storefront, cart and checkout, customer accounts and the admin backoffice.
//	@description	Every response uses the same envelope: `{ success, data, meta, error }`. Amounts are in satang (1 baht = 100 satang).
//	@description	Guests are identified by the `X-Guest-Session-ID` header (the API issues one on the first request and returns it in the same header).
//	@BasePath		/api/v1

//	@securityDefinitions.apikey	BearerAuth
//	@in							header
//	@name						Authorization
//	@description				JWT from /auth/login, sent as `Bearer <token>`.

//	@securityDefinitions.apikey	GuestSession
//	@in							header
//	@name						X-Guest-Session-ID
//	@description				Guest cart, wishlist and order session id.

func main() {
	logger := slog.New(slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{Level: slog.LevelInfo}))
	slog.SetDefault(logger)

	cfg := config.Load()
	slog.Info("starting aura-tech api server", "project", cfg.ProjectName, "port", cfg.APIPort)

	db, err := database.ConnectPostgres(cfg.DatabaseURL)
	if err != nil {
		slog.Warn("postgres not yet reachable at startup (will retry on boot in container)", "error", err)
	} else {
		if err := database.AutoMigrate(db); err != nil {
			slog.Error("failed to run database auto-migrations", "error", err)
		} else {
			var productCount int64
			if err := db.Model(&models.Product{}).Count(&productCount).Error; err == nil && productCount == 0 {
				slog.Info("no products found in database; seeding initial dataset...")
				if err := database.SeedAll(db); err != nil {
					slog.Error("automatic startup seeding failed", "error", err)
				} else {
					slog.Info("automatic startup seeding completed successfully")
					if err := database.OpenStockLedger(db); err != nil {
						slog.Error("failed to open stock ledger for seeded stock", "error", err)
					}
				}
			}
		}
	}

	storageClient, err := storage.NewMinIOClient(
		cfg.MinIOEndpoint,
		cfg.MinIORootUser,
		cfg.MinIORootPassword,
		cfg.MinIOBucketName,
		cfg.MinIOPublicURL,
		cfg.MinIOUseSSL,
	)
	var uploadImage func(r *http.Request, objectName string, body io.Reader, size int64, contentType string) (string, error)
	if err != nil {
		slog.Warn("minio not yet reachable at startup", "error", err)
	} else {
		uploadImage = func(r *http.Request, objectName string, body io.Reader, size int64, contentType string) (string, error) {
			return storageClient.Upload(r.Context(), objectName, body, size, contentType)
		}
	}

	// 1. Initialize Repositories
	userRepo := repository.NewUserRepository(db)
	bannerRepo := repository.NewBannerRepository(db)
	catalogRepo := repository.NewCatalogRepository(db)
	wishlistRepo := repository.NewWishlistRepository(db)
	cartRepo := repository.NewCartRepository(db)
	orderRepo := repository.NewOrderRepository(db)
	productAdminRepo := repository.NewProductAdminRepository(db)
	merchRepo := repository.NewMerchandisingRepository(db)
	engagementRepo := repository.NewEngagementRepository(db)
	importLookup := repository.NewProductImportLookup(db)
	auditRepo := repository.NewAuditRepository(db)
	reportRepo := repository.NewReportRepository(db)

	// 2. Initialize Services
	authService := service.NewAuthService(db, userRepo, wishlistRepo, cartRepo, cfg.JWTSecret)
	catalogService := service.NewCatalogService(catalogRepo, bannerRepo)
	interactionService := service.NewInteractionService(wishlistRepo, cartRepo)
	checkoutService := service.NewCheckoutService(orderRepo, cartRepo)
	adminService := service.NewAdminService(orderRepo)
	productAdminService := service.NewProductAdminService(productAdminRepo)
	merchService := service.NewMerchandisingService(merchRepo)
	engagementService := service.NewEngagementService(engagementRepo)
	importService := service.NewProductImportService(productAdminRepo, importLookup)
	auditService := service.NewAuditService(auditRepo)

	// 3. Initialize HTTP Handlers
	authHandler := handler.NewAuthHandler(authService)
	bannerHandler := handler.NewBannerHandler(catalogService)
	catalogHandler := handler.NewCatalogHandler(catalogService)
	wishlistHandler := handler.NewWishlistHandler(interactionService)
	cartHandler := handler.NewCartHandler(interactionService)
	checkoutHandler := handler.NewCheckoutHandler(checkoutService)
	adminHandler := handler.NewAdminHandler(adminService, auditService)
	productAdminHandler := handler.NewProductAdminHandler(productAdminService, auditService, uploadImage)
	merchHandler := handler.NewMerchandisingHandler(merchService, auditService)
	engagementHandler := handler.NewEngagementHandler(engagementService, auditService)
	importHandler := handler.NewProductImportHandler(importService, auditService)
	auditHandler := handler.NewAuditHandler(auditService)
	reportHandler := handler.NewReportHandler(reportRepo)

	// 4. Router Setup & Middleware Stack
	r := chi.NewRouter()

	r.Use(middleware.RequestID)
	r.Use(middleware.RealIP)
	r.Use(appMiddleware.RequestLoggerMiddleware)
	r.Use(middleware.Recoverer)
	r.Use(middleware.Timeout(60 * time.Second))

	r.Use(cors.Handler(cors.Options{
		AllowedOrigins:   []string{"http://localhost:5173", "http://localhost:3000", "http://127.0.0.1:5173"},
		AllowedMethods:   []string{"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"},
		AllowedHeaders:   []string{"Accept", "Authorization", "Content-Type", "X-CSRF-Token", "X-Guest-Session-ID", "X-Order-Email"},
		ExposedHeaders:   []string{"Link", "X-Guest-Session-ID"},
		AllowCredentials: true,
		MaxAge:           300,
	}))

	r.Use(appMiddleware.GuestSessionMiddleware)
	r.Use(appMiddleware.JWTOptionalMiddleware(cfg.JWTSecret))

	// Health Check
	r.Get("/health", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte(`{"status":"healthy","service":"aura-tech-api"}`))
	})

	// API reference (Swagger UI) at /swagger/index.html
	if cfg.SwaggerEnabled {
		r.Get("/swagger", func(w http.ResponseWriter, r *http.Request) {
			http.Redirect(w, r, "/swagger/index.html", http.StatusMovedPermanently)
		})
		r.Get("/swagger/*", httpSwagger.Handler(httpSwagger.URL("/swagger/doc.json")))
	}

	// 5. REST API v1 Routing
	r.Route("/api/v1", func(api chi.Router) {
		// Auth Routes
		api.Route("/auth", func(auth chi.Router) {
			auth.Post("/register", authHandler.Register)
			auth.Post("/login", authHandler.Login)
			auth.With(appMiddleware.RequireAuth).Get("/me", authHandler.Me)
			auth.With(appMiddleware.RequireAuth).Patch("/me", authHandler.UpdateMe)
			auth.With(appMiddleware.RequireAuth).Post("/change-password", authHandler.ChangePassword)
			auth.Post("/forgot-password", authHandler.ForgotPassword)
			auth.Post("/reset-password", authHandler.ResetPassword)
			auth.Get("/emails/{id}", authHandler.GetAccountEmail)
		})

		// Signed-in customer account
		api.Route("/account", func(acc chi.Router) {
			acc.Use(appMiddleware.RequireAuth)
			acc.Get("/orders", checkoutHandler.ListMyOrders)
			acc.Get("/emails", engagementHandler.ListAccountEmails)
			acc.Get("/stock-alerts", engagementHandler.ListStockAlerts)
			acc.Put("/stock-alerts/{variantID}", engagementHandler.SubscribeStockAlert)
			acc.Delete("/stock-alerts/{variantID}", engagementHandler.UnsubscribeStockAlert)
		})

		// Dynamic Component-Driven Banners
		api.Get("/banners", bannerHandler.GetBanners)

		// Catalog, Search & Comparison
		api.Get("/categories", catalogHandler.GetCategories)
		api.Get("/brands", catalogHandler.GetBrands)
		api.Get("/catalog", catalogHandler.GetCatalog)
		api.Get("/products/compare", catalogHandler.CompareProducts)
		api.Get("/products/{slug}", catalogHandler.GetProductBySlug)
		api.Get("/products/{slug}/reviews", engagementHandler.ProductReviews)
		api.Put("/products/{slug}/reviews/mine", engagementHandler.SaveReview)
		api.Delete("/products/{slug}/reviews/mine", engagementHandler.DeleteReview)
		api.Get("/search", catalogHandler.Search)

		// Wishlist (Dual User & Guest Support)
		api.Route("/wishlist", func(w chi.Router) {
			w.Get("/", wishlistHandler.GetWishlist)
			w.Post("/toggle", wishlistHandler.ToggleWishlist)
		})

		// Cart (Dual User & Guest Support)
		api.Route("/cart", func(c chi.Router) {
			c.Get("/", cartHandler.GetCart)
			c.Post("/items", cartHandler.AddToCart)
			c.Patch("/items/{id}", cartHandler.UpdateQuantity)
			c.Delete("/items/{id}", cartHandler.RemoveItem)
		})

		// Checkout & Mock Payment Gateway
		api.Route("/checkout", func(chk chi.Router) {
			chk.Post("/reserve", checkoutHandler.Reserve)
			chk.Post("/pay", checkoutHandler.Pay)
			chk.Get("/promptpay/{orderNumber}", checkoutHandler.GetPromptPayQR)
			chk.Get("/installments/{satangAmount}", checkoutHandler.CalculateInstallments)
		})

		// Orders
		api.Post("/orders/lookup", checkoutHandler.LookupOrder)
		api.Get("/orders/{orderNumber}", checkoutHandler.GetOrder)
		api.Get("/orders/{orderNumber}/emails", checkoutHandler.ListOrderEmails)
		api.Post("/orders/{orderNumber}/cancel", checkoutHandler.CancelOrder)

		// Admin Backoffice (Protected by Admin Role)
		api.Route("/admin", func(adm chi.Router) {
			adm.Use(appMiddleware.RequireAdmin)
			adm.Get("/overview", adminHandler.GetOverview)
			adm.Get("/orders", adminHandler.ListOrders)
			adm.Get("/products", productAdminHandler.ListProducts)
			adm.Post("/products", productAdminHandler.CreateProduct)
			adm.Get("/products/{id}", productAdminHandler.GetProduct)
			adm.Put("/products/{id}", productAdminHandler.UpdateProduct)
			adm.Patch("/products/{id}/status", productAdminHandler.SetStatus)
			adm.Post("/variants/{id}/stock-adjustments", productAdminHandler.AdjustStock)
			adm.Get("/variants/{id}/stock-movements", productAdminHandler.ListMovements)
			adm.Post("/uploads/images", productAdminHandler.UploadImage)
			adm.Get("/imports/products/columns", importHandler.Columns)
			adm.Get("/imports/products/export", importHandler.Export)
			adm.Post("/imports/products/preview", importHandler.Preview)
			adm.Post("/imports/products/commit", importHandler.Commit)
			adm.Patch("/orders/{id}/status", adminHandler.UpdateOrderStatus)
			adm.Get("/banners", merchHandler.ListBanners)
			adm.Post("/banners", merchHandler.CreateBanner)
			adm.Put("/banners/{id}", merchHandler.UpdateBanner)
			adm.Patch("/banners/{id}/status", merchHandler.SetBannerStatus)
			adm.Delete("/banners/{id}", merchHandler.DeleteBanner)
			adm.Get("/categories", merchHandler.ListCategories)
			adm.Post("/categories", merchHandler.CreateCategory)
			adm.Put("/categories/{id}", merchHandler.UpdateCategory)
			adm.Delete("/categories/{id}", merchHandler.DeleteCategory)
			adm.Get("/brands", merchHandler.ListBrands)
			adm.Post("/brands", merchHandler.CreateBrand)
			adm.Put("/brands/{id}", merchHandler.UpdateBrand)
			adm.Delete("/brands/{id}", merchHandler.DeleteBrand)
			adm.Get("/reviews", engagementHandler.ListReviewsAdmin)
			adm.Patch("/reviews/{id}", engagementHandler.SetReviewHidden)
			adm.Get("/audit-logs", auditHandler.List)
			adm.Get("/reports/sales", reportHandler.Sales)
			adm.Get("/reports/sales/export", reportHandler.Export)
		})
	})

	// Background worker: Periodically release expired 15-minute stock reservations
	ctxWorker, cancelWorker := context.WithCancel(context.Background())
	defer cancelWorker()

	if db != nil {
		go func() {
			ticker := time.NewTicker(1 * time.Minute)
			defer ticker.Stop()
			for {
				select {
				case <-ticker.C:
					if released, err := orderRepo.ReleaseExpiredReservations(ctxWorker); err == nil && released > 0 {
						slog.Info("released expired stock reservations", "count", released)
					}
				case <-ctxWorker.Done():
					return
				}
			}
		}()
	}

	server := &http.Server{
		Addr:         fmt.Sprintf(":%s", cfg.APIPort),
		Handler:      r,
		ReadTimeout:  15 * time.Second,
		WriteTimeout: 15 * time.Second,
		IdleTimeout:  60 * time.Second,
	}

	stopChan := make(chan os.Signal, 1)
	signal.Notify(stopChan, os.Interrupt, syscall.SIGTERM)

	go func() {
		slog.Info("http server listening", "addr", server.Addr)
		if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			slog.Error("server failed to start", "error", err)
			os.Exit(1)
		}
	}()

	<-stopChan
	slog.Info("shutdown signal received, gracefully draining connections...")

	ctxShutdown, cancelShutdown := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancelShutdown()

	if err := server.Shutdown(ctxShutdown); err != nil {
		slog.Error("server forced to shutdown", "error", err)
		os.Exit(1)
	}

	slog.Info("server shutdown gracefully completed")
}
